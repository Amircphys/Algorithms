"""
Алгоритм Хоара, также известный как Quickselect, — это элегантный и эффективный алгоритм для нахождения
k-ой порядковой статистики (например, k-го наименьшего элемента) в неотсортированном массиве.

Давайте разберем его максимально подробно и ясно.

### 1. Что такое k-я порядковая статистика?

**Порядковая статистика** — это элемент, который занимает k-ю позицию в отсортированном массиве.
*   **1-я порядковая статистика** — это минимальный элемент.
*   **n-я порядковая статистика** (где n — длина массива) — это максимальный элемент.
*   **Медиана** — это порядковая статистика с k = n/2.

Задача: найти такой элемент, **не сортируя весь массив полностью**.

---

### 2. Идея алгоритма Хоара (Quickselect)

Идея алгоритма очень похожа на его "старшего брата" — быструю сортировку (Quicksort), и основана на стратегии **"разделяй и властвуй"**.

**Ключевая мысль:** после того как мы выбрали "опорный элемент" (pivot) и переупорядочили массив (сделали partition), мы точно знаем:
1.  Позицию, на которую встал опорный элемент после разделения.
2.  Все элементы слева от него **не больше** (≤) опорного.
3.  Все элементы справа от него **не меньше** (≥) опорного.

**В отличие от Quicksort, который рекурсивно обрабатывает обе части, Quickselect делает рекурсивный вызов только в той одной части,
где заведомо находится искомый k-й элемент.** Это и делает его значительно быстрее в среднем.

---

### 3. Алгоритм шаг за шагом

**Вход:** Массив `A`, левая граница `left`, правая граница `right`, индекс `k` (чаще от 0 до n-1, где 0 — минимум).
**Выход:** Значение k-й порядковой статистики.

1.  **Базовый случай:** Если `left == right`, это означает, что в текущем подмассиве всего один элемент. Мы его и возвращаем. `(A[left])`.

2.  **Выбор опорного элемента (pivot):** Выбираем произвольный элемент из текущего подмассива. Для простоты и эффективности
в среднем часто берут последний или случайный. Пусть `pivot_index = right` (последний элемент).

3.  **Разделение (Partition):** Это самая важная часть.
    *   Цель: переупорядочить массив так, чтобы все элементы меньше опорного оказались слева, а больше — справа. Сам опорный элемент
    встанет на свою итоговую позицию.
    *   Заводим переменную-счетчик `i = left` (она будет указывать на конец области элементов, *меньших* опорного).
    *   Проходим циклом `j` от `left` до `right - 1` (т.е. по всем элементам, кроме самого опорного).
    *   Если `A[j] <= A[pivot_index]` (опорный элемент), то меняем местами `A[i]` и `A[j]` и увеличиваем `i` на 1.
    *   После прохода по всем элементам меняем местами опорный элемент (`A[pivot_index]`) и первый элемент из "большей" группы (`A[i]`).
    Теперь опорный элемент стоит на своей окончательной позиции `i`.
    *   **Результат этапа:** Мы знаем индекс `i`, на котором теперь находится опорный элемент. Это его итоговый ранг в массиве.

4.  **Сравнение `i` и `k`:**
    *   Если `i == k`: Удача! Опорный элемент и есть тот самый k-й элемент. Возвращаем `A[i]`.
    *   Если `k < i`: Искомый k-й элемент находится в *левой* части (среди элементов, меньших опорного). Рекурсивно вызываем алгоритм
    для диапазона `[left, i - 1]`.
    *   Если `k > i`: Искомый k-й элемент находится в *правой* части (среди элементов, больших опорного). Рекурсивно вызываем алгоритм
    для диапазона `[i + 1, right]`.

**Важно:** После шага partition массив частично упорядочен, и мы можем отбросить как минимум одну часть, что экономит много вычислений.
"""


def quickselect(arr, left, right, k):
    if left == right:
        return arr[left]

    pivot_index = random.randint(left, right)
    arr[pivot_index], arr[right] = arr[right], arr[pivot_index]

    i = left
    for j in range(left, right):
        if arr[j] <= arr[right]:
            arr[i], arr[j] = arr[j], arr[i]
            i += 1

    arr[i], arr[right] = arr[right], arr[i]

    if k == i:
        return arr[i]
    elif k < i:
        return quickselect(arr, left, i - 1, k)
    else:
        return quickselect(arr, i + 1, right, k)


print(quickselect([0, 2, 5, 3, 4, 1, 6], 0, 6, 1))
